"""Generate the in-game settings catalog from the maintained config layout."""
from pathlib import Path
import re
try:
    from .config_layout import SECTIONS
except ImportError:
    from config_layout import SECTIONS

ROOT = Path(__file__).resolve().parents[1]

def render():
    source = (ROOT/'scripting/premium/config.inc').read_text(encoding='utf-8')
    numbers = {n: v for n,v in re.findall(r'Setting\("(premium_[^"]+)",\s*"([^"]*)"', source)}
    for cls in ('scout','sniper','soldier','demoman','medic','heavy','pyro','spy','engineer'):
        numbers['premium_speedmult_'+cls] = '1.0'
    sections = SECTIONS[:-1]  # Storage changes stay in the file: queued operations bind to a backend.
    names, labels, groups, numeric, steps = [], [], [], [], []
    for group, (_,_,settings) in enumerate(sections):
        for name, label in settings:
            names.append(name); labels.append(label.split(';')[0].rstrip('.')); groups.append(group); numeric.append(name in numbers)
            steps.append(0.05 if '.' in numbers.get(name,'') else 0.25 if any(s in name for s in ('multiplier','gravity_mult')) else 1.0)
    titles = ['Main switches','Membership & free trials','Points: earning','Points: purchases & trials','Engineer','Health, ammo & respawn',
              'Movement & class speed','Pyro flight & airblast','Class bonuses','Team swap & teleport','Chat & appearance','Adverts & announcements']
    def strings(name, values):
        rows = ',\n'.join('    "'+v.replace('\\','\\\\').replace('"','\\"')+'"' for v in values)
        return f'char {name}[][] = {{\n{rows}\n}};\n'
    output = '// Generated by tools/prepare_ui.py; definitions come from config_layout.py and config.inc.\n'
    output += strings('g_UiSettingSections',titles)+strings('g_UiSettingNames',names)+strings('g_UiSettingLabels',labels)
    output += 'int g_UiSettingSection[] = {'+', '.join(map(str,groups))+'};\n'
    output += 'bool g_UiSettingNumeric[] = {'+', '.join('true' if x else 'false' for x in numeric)+'};\n'
    output += 'float g_UiSettingStep[] = {'+', '.join(str(x) for x in steps)+'};\n'
    return output, len(names), sum(numeric)

def generate():
    output, count, editors = render()
    (ROOT/'scripting/premium/ui_settings_data.inc').write_text(output,encoding='utf-8',newline='\n')
    return count, editors

if __name__ == '__main__': print('Generated menu catalog: %d settings, %d numeric editors.' % generate())
